import { expect, test } from '@playwright/test'
import { verifyExport } from './t060-export'
function required(name: string) { const value = process.env[name]; if (!value) throw new Error(`Harness must provide ${name}`); return value }
test('real one-epoch CPU training persists metrics, reloads final weights and downloads both models, then optionally verifies ONNX export', async ({ page }) => {
  test.skip(process.env.EDGEVISION_E2E_ML !== '1', 'Requires explicit hash-locked Linux CPU environment')
  test.setTimeout(process.env.EDGEVISION_E2E_DELIVERY === '1' ? 360_000 : 180_000)
  await page.goto('/')
  await page.getByLabel('用户名', {exact:true}).fill(required('EDGEVISION_E2E_ADMIN_USERNAME'))
  await page.getByLabel('密码', {exact:true}).fill(required('EDGEVISION_E2E_ADMIN_PASSWORD'))
  await page.getByRole('button', {name:'登录',exact:true}).click()
  await page.getByLabel('项目名称').fill(`training-${Date.now()}`)
  const created = page.waitForResponse(response => response.url().endsWith('/api/v1/projects') && response.request().method()==='POST')
  await page.getByRole('button', {name:'创建项目'}).click()
  const project = await (await created).json()
  await page.getByLabel('所属项目').selectOption(project.id)
  await page.getByLabel('受控 YOLO ZIP').setInputFiles(required('EDGEVISION_E2E_TRAINING_ZIP'))
  await page.getByRole('button', {name:'上传新快照'}).click()
  const row=page.locator('article.dataset-row').filter({hasText:'training-dataset · v1'})
  await row.getByRole('button',{name:'开始校验'}).click()
  await expect(row).toContainText('ready',{timeout:20000})
  const panel=page.locator('.training-panel')
  await panel.getByLabel('训练数据集').selectOption({label:'training-dataset · v1'})
  await panel.getByLabel('实验名称').fill('Browser CPU smoke')
  const submitted=page.waitForResponse(response => response.url().endsWith(`/projects/${project.id}/jobs`) && response.request().method()==='POST')
  await panel.getByRole('button',{name:'创建训练任务'}).evaluate((button: HTMLButtonElement) => {button.click();button.click()})
  const response=await submitted;expect(response.status()).toBe(202)
  const job=await response.json()
  await expect(panel.locator('h3')).toContainText('succeeded',{timeout:120000})
  await expect(panel).toContainText('最终指标已读取')
  await expect(panel).toContainText('已完成 1 / 1 轮')
  await expect(panel.getByRole('link',{name:/下载 pt_/})).toHaveCount(2)
  for (const link of await panel.getByRole('link',{name:/下载 pt_/}).all()) {
    const downloaded=await page.request.get((await link.getAttribute('href'))!);expect(downloaded.status()).toBe(200);expect((await downloaded.body()).length).toBeGreaterThan(1000000)
  }
  const metrics=await (await page.request.get(`/api/v1/jobs/${job.job_id}/metrics`)).json()
  expect(metrics.items).toHaveLength(10);expect(metrics.items.every((item:{epoch:number,value:number})=>item.epoch===1&&Number.isFinite(item.value))).toBe(true)
  await page.reload();await page.getByLabel('所属项目').selectOption(project.id)
  await expect(page.locator('.training-panel')).toContainText('最终指标已读取')
  if (process.env.EDGEVISION_E2E_DELIVERY === '1') await verifyExport(page, project.id, job.job_id)
  await page.setViewportSize({width:375,height:812})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
})
